/// الشروط · الخصوصية · إرشادات المجتمع — نسخة أولية (تُراجع مع محامٍ قبل النشر في المتاجر)
class LegalPage extends StatelessWidget {
  final String title, body;
  const LegalPage({super.key, required this.title, required this.body});

  static Future<void> open(BuildContext context, {bool terms = false, bool guidelines = false}) {
    final page = guidelines
        ? const LegalPage(title: 'إرشادات المجتمع', body: _guidelines)
        : terms
            ? const LegalPage(title: 'شروط الاستخدام', body: _terms)
            : const LegalPage(title: 'سياسة الخصوصية', body: _privacy);
    return Navigator.of(context).push(MaterialPageRoute(builder: (_) => page));
  }

  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(title: Text(title)),
        body: SingleChildScrollView(
          padding: const EdgeInsets.fromLTRB(20, 8, 20, 40),
          child: SelectableText(body, style: E.t(14.5, c: E.ink2, h: 1.7)),
        ),
      );
}

